export const generateWishTemplates = (
  occasionId: string,
  styleId: string,
  customOccasion: string,
  recipient: string
): string[][] => {
  const name = recipient || 'প্রিয়জন';
  const isProfessional = styleId === 'professional';
  const salutation = isProfessional ? `শ্রদ্ধেয় ${name},` : `প্রিয় ${name},`;

  const templates: string[][] = [];

  // ================= BIRTHDAY =================
  if (occasionId === 'birthday') {
    if (styleId === 'funny') {
      templates.push([
        salutation,
        `শুভ জন্মদিন! দিন দিন তোমার বয়স তো বাড়ছে, কিন্তু বুদ্ধি কি আদৌ বাড়ছে?`,
        `যাই হোক, আজকের দিনটা অনেক আনন্দে কাটুক। আর হ্যাঁ, ট্রিট কবে দিচ্ছ সেটা তাড়াতাড়ি কনফার্ম করো!`,
        `খুব ভালো থেকো।`
      ]);
      templates.push([
        salutation,
        `জন্মদিনের অনেক অনেক শুভেচ্ছা! আশা করি তুমি আরও অনেক বছর বাঁচবে, অন্তত আমার ধার শোধ করার আগ পর্যন্ত!`,
        `মজা করলাম! আজকের দিনটা দারুণভাবে উপভোগ করো।`
      ]);
    } else if (styleId === 'emotional') {
      templates.push([
        salutation,
        `শুভ জন্মদিন! তুমি আমার জীবনের সবচেয়ে সুন্দর উপহারগুলোর একটি।`,
        `তোমার হাসিমুখ আমাকে সবসময় ভালো থাকার অনুপ্রেরণা দেয়। আমি চাই তুমি সবসময় এমন হাসি-খুশি থেকো।`,
        `পৃথিবীর সব সুখ যেন তোমার হয়। অনেক অনেক ভালোবাসা।`
      ]);
    } else if (styleId === 'religious') {
      templates.push([
        salutation,
        `শুভ জন্মদিন। মহান আল্লাহ তায়ালা তোমাকে নেক হায়াত দান করুন।`,
        `জীবনের প্রতিটি পদক্ষেপে আল্লাহ তোমার সহায় হোন এবং দ্বীনের পথে চলার তৌফিক দিন।`,
        `দোয়া করি, দুনিয়া ও আখিরাতে তুমি কামিয়াব হও।`
      ]);
    } else if (styleId === 'poetic') {
      templates.push([
        salutation,
        `আজ বাতাসে নতুন সুর, আলোতে নতুন সাজ,`,
        `তোমার জন্মদিন বলে পৃথিবী হাসছে আজ।`,
        `এভাবেই হাসিখুশি থেকো সারাজীবন,`,
        `শুভ জন্মদিন, ভালো থেকো অনুক্ষণ।`
      ]);
    } else if (styleId === 'professional') {
      templates.push([
        salutation,
        `জন্মদিনের আন্তরিক শুভেচ্ছা ও অভিনন্দন।`,
        `আপনার সুস্বাস্থ্য, দীর্ঘায়ু এবং পেশাগত জীবনে উত্তরোত্তর সাফল্য কামনা করছি।`,
        `শুভ জন্মদিন।`
      ]);
    } else {
      templates.push([
        salutation,
        `শুভ জন্মদিন! আজকের এই বিশেষ দিনে তোমার জন্য রইল অনেক অনেক শুভকামনা।`,
        `তোমার আগামী দিনগুলো হোক আরও সুন্দর, সাফল্যমণ্ডিত ও আনন্দময়।`,
        `সবসময় ভালো থেকো।`
      ]);
    }
  } 
  
  // ================= ANNIVERSARY =================
  else if (occasionId === 'anniversary') {
    if (styleId === 'funny') {
      templates.push([
        salutation,
        `শুভ বিবাহ বার্ষিকী! এতগুলো বছর একসাথে পার করে দিলে, মানতেই হবে তোমাদের সহ্যশক্তি অনেক বেশি!`,
        `দোয়া করি এভাবেই ঝগড়া-ভালোবাসার মধ্য দিয়ে সারা জীবন পার করে দাও।`
      ]);
    } else if (styleId === 'emotional') {
      templates.push([
        salutation,
        `শুভ বিবাহ বার্ষিকী! তোমাদের দুজনের ভালোবাসা যেন সময়ের সাথে সাথে আরও গভীর হয়।`,
        `তোমাদের একসাথে পথচলা আমার কাছে এক চমৎকার অনুপ্রেরণা। সারাজীবন এভাবেই একে অপরের হাত ধরে থেকো।`
      ]);
    } else if (styleId === 'religious') {
      templates.push([
        salutation,
        `শুভ বিবাহ বার্ষিকী। আল্লাহ তায়ালা তোমাদের দাম্পত্য জীবনে রহমত ও বরকত দান করুন।`,
        `দোয়া করি, তোমাদের দুজনের মধ্যে ভালোবাসা ও বোঝাপড়া আজীবন অটুট থাকুক।`
      ]);
    } else {
      templates.push([
        salutation,
        `শুভ বিবাহ বার্ষিকী! আজকের এই বিশেষ দিনে তোমাদের দুজনের জন্যই রইল অনেক শুভকামনা।`,
        `আগামীর প্রতিটি দিন যেন তোমাদের জন্য নতুন আনন্দের বার্তা নিয়ে আসে।`
      ]);
    }
  }
  
  // ================= EID =================
  else if (occasionId === 'eid') {
    if (styleId === 'funny') {
      templates.push([
        salutation,
        `ঈদ মোবারক! এবারের ঈদে সেলামি কিন্তু আমি আগে পাব, এটা যেন মনে থাকে!`,
        `ঈদের দিনটা অনেক মজার কাটুক আর অনেক অনেক খাওয়া-দাওয়া হোক।`
      ]);
    } else if (styleId === 'poetic') {
      templates.push([
        salutation,
        `আকাশে উঠেছে নতুন চাঁদ, কেটে গেছে সব বিষাদ।`,
        `ঈদের আনন্দে মেতে উঠুক তোমার মন,`,
        `ঈদ মোবারক জানাই তোমায়, ওগো প্রিয়জন।`
      ]);
    } else if (styleId === 'religious') {
      templates.push([
        salutation,
        `তাকাব্বালাল্লাহু মিন্না ওয়া মিনকুম। ঈদ মোবারক।`,
        `আল্লাহ তায়ালা আমাদের সবার ইবাদত কবুল করুন এবং এই ঈদের উসিলায় আমাদের গুনাহগুলো মাফ করে দিন।`
      ]);
    } else {
      templates.push([
        salutation,
        `ঈদ মোবারক! ঈদের এই আনন্দ তোমার জীবনে বয়ে আনুক অনাবিল শান্তি ও সুখ।`,
        `পরিবারের সবাইকে নিয়ে খুব সুন্দর আর আনন্দময় একটি ঈদ কাটাও।`
      ]);
    }
  }
  
  // ================= NEW YEAR =================
  else if (occasionId === 'newyear') {
    if (styleId === 'funny') {
      templates.push([
        salutation,
        `শুভ নববর্ষ! নতুন বছরে আশা করি তোমার পুরোনো সব বদভ্যাস পাল্টে যাবে (যদিও আমার মনে হয় না!)।`,
        `যাই হোক, নতুন বছরটা দারুণ কাটুক!`
      ]);
    } else if (styleId === 'poetic') {
      templates.push([
        salutation,
        `নতুন সূর্য, নতুন প্রাণ, নতুন সুরে গাও গান।`,
        `নতুন বছর নিয়ে আসুক অনাবিল সুখের জোয়ার,`,
        `শুভ নববর্ষ তোমায় জানাই বারবার।`
      ]);
    } else {
      templates.push([
        salutation,
        `শুভ নববর্ষ! পুরোনো সব গ্লানি ভুলে নতুন বছর তোমার জীবনে নতুন আশা ও সম্ভাবনা নিয়ে আসুক।`,
        `আগামী দিনগুলো হোক আনন্দে ভরপুর।`
      ]);
    }
  }
  
  // ================= SPECIAL / OTHER =================
  else {
    const occLabel = customOccasion || 'বিশেষ দিন';
    if (styleId === 'funny') {
      templates.push([
        salutation,
        `আজকের এই ${occLabel}-এ তোমাকে অনেক অনেক শুভেচ্ছা!`,
        `এমন খুশির দিনেও যদি ট্রিট না দাও, তবে আর কবে দেবে? দারুণ কাটাও আজকের দিনটা!`
      ]);
    } else if (styleId === 'emotional') {
      templates.push([
        salutation,
        `আজকের এই ${occLabel}-এ তোমাকে জানাই আমার হৃদয়ের গভীর থেকে ভালোবাসা।`,
        `তোমার জীবনের প্রতিটি বিশেষ মুহূর্ত এভাবেই আমার সাথে শেয়ার করো। ভালো থেকো সবসময়।`
      ]);
    } else if (styleId === 'poetic') {
      templates.push([
        salutation,
        `আজকের এই ${occLabel}-এ বাতাসে বইছে সুর,`,
        `তোমার সব স্বপ্নগুলো যাক পৌঁছে বহুদূর।`,
        `অনেক অনেক শুভকামনা তোমার জন্য।`
      ]);
    } else if (styleId === 'religious') {
      templates.push([
        salutation,
        `আজকের এই ${occLabel}-এ মহান আল্লাহর দরবারে তোমার জন্য দোয়া করছি।`,
        `তিনি যেন তোমার প্রতিটি ভালো কাজ কবুল করেন এবং তোমাকে দুনিয়া ও আখিরাতে সফলতা দান করেন।`
      ]);
    } else if (styleId === 'professional') {
      templates.push([
        salutation,
        `আজকের এই ${occLabel} উপলক্ষে আপনাকে জানাই আন্তরিক শুভেচ্ছা।`,
        `আমি আপনার সর্বাঙ্গীণ সাফল্য এবং সুস্বাস্থ্য কামনা করছি।`
      ]);
    } else {
      templates.push([
        salutation,
        `আজকের এই বিশেষ ${occLabel}-এ তোমার জন্য রইল অনেক অনেক শুভেচ্ছা।`,
        `তোমার আগামী দিনগুলো হোক সুখ, শান্তি ও সফলতায় ভরা।`
      ]);
    }
  }

  // Fallback if empty (should not happen, but just in case)
  if (templates.length === 0) {
    templates.push([
      salutation,
      `অনেক অনেক শুভেচ্ছা ও শুভকামনা রইল।`,
      `জীবনের প্রতিটি পদক্ষেপে তুমি সফল হও, এটাই আমার কামনা।`
    ]);
  }

  return templates;
};
